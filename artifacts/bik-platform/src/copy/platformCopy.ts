export type PlatformCopyKey = keyof typeof platformCopy;

/** Insert only variables declared by the selected approved template. */
export function formatPlatformCopy(key: PlatformCopyKey, values: Record<string, string | number> = {}): string {
  const allowed: readonly string[] = platformCopyRules[key].variables;
  for (const name of Object.keys(values)) if (!allowed.includes(name)) throw new Error(`Unexpected copy variable: ${key}.${name}`);
  for (const name of allowed) if (!Object.hasOwn(values, name)) throw new Error(`Missing copy variable: ${key}.${name}`);
  return platformCopy[key].replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name]));
}
